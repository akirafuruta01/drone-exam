/**
 * 出題のたびに言い回しを少し変える（丸暗記を防ぐため）。
 * 意味が変わらない言い換えだけを、ランダムに組み合わせて使う。
 */

/** 文字列から決まる乱数（模擬試験と結果画面で同じ文章にするため） */
export function seededRandom(seed: number) {
  let a = seed >>> 0;
  return () => {
    a = (a + 0x6d2b79f5) >>> 0;
    let t = a;
    t = Math.imul(t ^ (t >>> 15), t | 1);
    t ^= t + Math.imul(t ^ (t >>> 7), t | 61);
    return ((t ^ (t >>> 14)) >>> 0) / 4294967296;
  };
}

type Rand = () => number;
const pick = <T,>(r: Rand, list: readonly T[]) => list[Math.floor(r() * list.length)];

/** 問題文の終わりの言い方 */
const STEMS: [RegExp, string[]][] = [
  [/最も適切なものはどれか。$/, ["最も適切なものはどれか。", "いちばん適切なものを1つ選べ。", "最も妥当なものはどれか。"]],
  [/正しいものはどれか。$/, ["正しいものはどれか。", "正しいものを1つ選べ。", "適切なものはどれか。", "妥当なものを1つ選びなさい。"]],
  [/正しい記述はどれか。$/, ["正しい記述はどれか。", "正しい記述を1つ選べ。", "適切な記述はどれか。"]],
  [/正しいものを選べ。$/, ["正しいものを選べ。", "正しいものはどれか。", "適切なものを1つ選びなさい。"]],
  [/誤っているものはどれか。$/, ["誤っているものはどれか。", "誤りを含むものを1つ選べ。", "不適切なものはどれか。"]],
  [/誤っている記述はどれか。$/, ["誤っている記述はどれか。", "誤りを含む記述を1つ選べ。", "不適切な記述はどれか。"]],
  [/該当しないものはどれか。$/, ["該当しないものはどれか。", "あてはまらないものを1つ選べ。", "該当しないものを選びなさい。"]],
  [/あたらないものはどれか。$/, ["あたらないものはどれか。", "あてはまらないものを1つ選べ。"]],
  [/挙げられていないものはどれか。$/, ["挙げられていないものはどれか。", "挙げられていないものを1つ選べ。"]],
  [/示されているものはどれか。$/, ["示されているものはどれか。", "示されているものを1つ選べ。"]],
];

/** 意味の変わらない言い換え（左右どちらにも変えられる） */
const SWAPS: [string, string][] = [
  ["飛行させることができる", "飛ばすことができる"],
  ["飛行させる", "飛ばす"],
  ["飛行させて", "飛ばして"],
  ["飛行させた", "飛ばした"],
  ["飛行させない", "飛ばさない"],
  ["あらかじめ", "事前に"],
  ["ただちに", "すぐに"],
  ["直ちに", "すぐに"],
  ["確認する", "確かめる"],
  ["確認して", "確かめて"],
  ["確認した", "確かめた"],
  ["場合は", "ときは"],
  ["場合も", "ときも"],
  ["場合でも", "ときでも"],
  ["又は", "または"],
  ["一般に、", "一般的に、"],
  ["必要がある", "必要となる"],
];

/** 1つの文に、言い換えをランダムに当てはめる */
export function varyText(text: string, r: Rand, isStem = false) {
  let t = text;
  if (isStem) {
    for (const [re, list] of STEMS) {
      if (re.test(t)) {
        t = t.replace(re, pick(r, list));
        break;
      }
    }
  }
  for (const [a, b] of SWAPS) {
    if (r() < 0.5) continue;
    if (t.includes(a)) t = t.split(a).join(b);
    else if (t.includes(b) && a !== "直ちに") t = t.split(b).join(a);
  }
  // 理由を表す「〜るため、」「〜いため、」を「〜ので、」に（「安全のため、」などは変えない）
  if (r() < 0.5) t = t.replace(/([るいた])ため、/g, "$1ので、");
  return t;
}
